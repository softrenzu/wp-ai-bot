from textwrap import dedent
from itertools import product


def get_static_templates_text() -> str:
    """
    民泊 × 幡ヶ谷 × 集客 のテーマの「型」を
    コード内で自動的に大量生成してテキスト化する。
    """

    base_categories = [
        "幡ヶ谷の魅力・街の雰囲気",
        "幡ヶ谷からのアクセス・移動方法",
        "幡ヶ谷周辺の観光スポット",
        "幡ヶ谷周辺の飲食店・グルメ情報",
        "幡ヶ谷での子連れ・家族旅行",
        "幡ヶ谷での一人旅・女性一人旅",
        "幡ヶ谷での長期滞在・ワーケーション",
        "幡ヶ谷民泊と周辺イベントの組み合わせ",
        "幡ヶ谷民泊に泊まるときの不安解消・Q&A",
        "幡ヶ谷民泊を拠点にした東京観光モデルコース",
    ]

    targets = [
        "カップル旅行",
        "子連れファミリー",
        "女性一人旅",
        "男性一人旅",
        "友人グループ",
        "ビジネス出張",
        "長期滞在ワーカー",
        "外国人旅行者",
    ]

    intents = [
        "不安を解消する",
        "宿泊のイメージを具体的に持ってもらう",
        "幡ヶ谷に泊まるメリットを理解してもらう",
        "周辺施設の利便性を伝える",
        "夜の治安や雰囲気を伝える",
        "子連れでも安心できることを伝える",
        "深夜・早朝の移動のしやすさを伝える",
        "飲食店やカフェの充実度を伝える",
        "イベントと合わせた滞在の楽しさを伝える",
    ]

    seasons = [
        "春（花見・新生活シーズン）",
        "夏（夏祭り・海・花火シーズン）",
        "秋（紅葉・連休・行楽シーズン）",
        "冬（年末年始・イルミネーションシーズン）",
        "ゴールデンウィーク",
        "シルバーウィーク",
        "受験・就活シーズン",
        "ライブ・イベント集中シーズン",
    ]

    patterns = []
    for cat, tgt, it, season in product(base_categories, targets, intents, seasons):
        patterns.append(
            f"- カテゴリ: {cat} / ターゲット: {tgt} / 目的: {it} / 時期: {season}"
        )

    text = dedent(
        f"""
        以下は、幡ヶ谷エリアの民泊集客用ブログ記事で取りうる
        多数の切り口パターンの一部例です。

        それぞれのパターンは、
        - 幡ヶ谷という地名
        - 民泊（宿泊）
        - 誰が泊まるのか（ターゲット）
        - どんな目的・不安・期待を持っているか
        - どの時期に泊まるのか（季節・イベント）

        を組み合わせた「テーマの型」を表しています。

        これらの型を参考にしつつ、
        過去記事と重複しない新しいテーマを1つだけ考えてください。

        テーマの型一覧（抜粋）:
        {chr(10).join(patterns[:400])}

        ※実際には同様のパターンが多数存在すると考えてください。
        """
    ).strip()

    return text
